    private val byRegistrable: Map<String, TrackerDomain> = all.filter { !it.exactHost }.associateBy { it.domain }
    private val byHost: Map<String, TrackerDomain> = all.filter { it.exactHost }.associateBy { it.domain }

    /** The entry [host] belongs to, or null. Exact-host entries win over registrable ones. */
    fun match(host: String): TrackerDomain? {
        val h = PublicSuffix.normalize(host)
        if (h.isEmpty()) return null
        var start = 0
        while (true) {
            byHost[h.substring(start)]?.let { return it }
            val dot = h.indexOf('.', start)
            if (dot < 0) break
            start = dot + 1
        }
        return byRegistrable[PublicSuffix.registrableDomain(h)]
    }

    fun isTracker(host: String): Boolean = match(host) != null

    fun byDomain(domain: String): TrackerDomain? = byHost[domain] ?: byRegistrable[domain]
}
