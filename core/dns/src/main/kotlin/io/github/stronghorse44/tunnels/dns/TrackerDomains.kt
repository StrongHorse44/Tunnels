package io.github.stronghorse44.tunnels.dns

enum class TrackerKind(val label: String) {
    ADS("ads"),
    ANALYTICS("analytics"),
    ATTRIBUTION("attribution"),
    CRASH("crash reporting"),
    PUSH("push"),
    TELEMETRY("telemetry"),
    SOCIAL("social"),
}

/**
 * One tracking endpoint. [exactHost] entries name a host (and its subdomains) under a domain that is
 * otherwise innocent, like `graph.facebook.com`; the rest name a whole registrable domain.
 */
data class TrackerDomain(val domain: String, val kind: TrackerKind, val vendor: String, val exactHost: Boolean = false)

